#!/usr/bin/env python3
"""Residential proxy benchmark - 95% confidence intervals of pairwise differences.

The workbook gives Wilson intervals for rates (Success Rate, Geo Accuracy, ...),
and the compare pages call a tie when two such intervals overlap. Latency and
Duplicate Rate have no interval there, so this script computes one for the
difference between two providers, from the raw infrastructure logs:

  latency, latency-p90  median / P90 of request time on successful requests,
                        pooled over all runs as in the workbook; bootstrap
                        that resamples whole runs (server x run_id), because
                        requests inside one run are not independent.
  duplicate             1 - unique IPs / successful requests per run, paired
                        by run; bootstrap of the mean per-run difference
                        (resampling whole runs never duplicates an IP).

A difference whose interval contains 0 is a tie on the compare pages.

Only the Python standard library is used. Example:

  python3 scripts/pairs.py --raw data/raw --out pairs.json
  python3 scripts/pairs.py --raw data/raw --ts ../floppydata-landing/src/data/benchmarkPairs.ts
"""
import argparse
import csv
import glob
import json
import os
import random
import statistics
from collections import defaultdict

# Display names as on floppydata.com; the CSVs use the lowercase key.
PROVIDERS = ["Decodo", "Oxylabs", "Evomi", "SOAX", "DataImpulse", "Rayobyte", "ProxyEmpire",
             "Webshare", "NodeMaven", "IPRoyal", "Floppydata", "Geonode"]
OWN = "Floppydata"


def load(raw):
    """provider key -> run (server/run_id) -> list of (sec, ip) of successful requests."""
    runs = defaultdict(lambda: defaultdict(list))
    for path in sorted(glob.glob(os.path.join(raw, "*", "infra_*.csv"))):
        with open(path, newline="") as f:
            for r in csv.DictReader(f):
                if r["ok"] == "1":
                    runs[r["provider"]][r["server"] + "/" + r["run_id"]].append((float(r["sec"]), r["ip"]))
    return runs


def median_p90(values):
    s = sorted(values)
    return statistics.median(s), s[int(0.9 * (len(s) - 1))]


def dup(rows):
    return 1 - len(set(ip for _, ip in rows)) / len(rows)


def pair(runs, a, b, reps, rng):
    ra, rb = runs[a.lower()], runs[b.lower()]
    ca, cb = list(ra.values()), list(rb.values())
    lat_d, p90_d = [], []
    for _ in range(reps):
        ma, pa = median_p90([s for c in rng.choices(ca, k=len(ca)) for s, _ in c])
        mb, pb = median_p90([s for c in rng.choices(cb, k=len(cb)) for s, _ in c])
        lat_d.append(ma - mb)
        p90_d.append(pa - pb)
    shared = sorted(set(ra) & set(rb))
    per_run = [100 * (dup(ra[k]) - dup(rb[k])) for k in shared]
    dup_d = [statistics.mean(rng.choices(per_run, k=len(per_run))) for _ in range(reps)]

    def ci(d):
        d.sort()
        return [round(d[int(0.025 * reps)], 4), round(d[int(0.975 * reps) - 1], 4)]

    return {"latency": ci(lat_d), "latency-p90": ci(p90_d), "duplicate": ci(dup_d), "runs": len(shared)}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw", default="data/raw", help="folder with us/, de/, sg/ raw CSVs")
    ap.add_argument("--all", action="store_true", help="every pair, not only Floppydata against the others")
    ap.add_argument("--reps", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--out", default="", help="write JSON here")
    ap.add_argument("--ts", default="", help="write a TypeScript module here (for the website)")
    args = ap.parse_args()

    runs = load(args.raw)
    rng = random.Random(args.seed)
    if args.all:
        pairs = [(a, b) for i, a in enumerate(PROVIDERS) for b in PROVIDERS[i + 1:]]
    else:
        pairs = [(OWN, b) for b in PROVIDERS if b != OWN]
    result = {}
    for a, b in pairs:
        result["%s|%s" % (a, b)] = pair(runs, a, b, args.reps, rng)
        print("%-25s latency %s  p90 %s  duplicate %s" % (
            a + " vs " + b, result["%s|%s" % (a, b)]["latency"],
            result["%s|%s" % (a, b)]["latency-p90"], result["%s|%s" % (a, b)]["duplicate"]))

    if args.out:
        with open(args.out, "w") as f:
            json.dump(result, f, indent=1)
    if args.ts:
        with open(args.ts, "w") as f:
            f.write(
                "/*\n"
                " * GENERATED by scripts/pairs.py in Floppydata/residential-proxy-benchmark-2026\n"
                " * (seed %d, %d bootstrap resamples) from the raw infrastructure logs;\n"
                " * regenerate rather than edit. 95%% confidence interval of the difference\n"
                " * \"first minus second\" of the key: latency and latency-p90 in seconds,\n"
                " * duplicate in percentage points (mean per-run difference). An interval\n"
                " * containing 0 is a tie on the compare pages.\n"
                " */\n\n"
                "export const pairDiffs: Record<string, Record<string, [number, number]>> = %s;\n"
                % (args.seed, args.reps,
                   json.dumps({k: {m: v[m] for m in ("latency", "latency-p90", "duplicate")}
                               for k, v in result.items()}, indent=4)))


if __name__ == "__main__":
    main()
